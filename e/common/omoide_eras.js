// 生まれ年 y の人が「はい」と答える確率：その人の「思い出の年齢」の期間と、流行の期間が重なるほど高い
function eraProb(e, y) {
  const [, , b0, b1, a0, a1] = e, s = y + a0, t = y + a1;
  const ov = Math.min(b1, t) - Math.max(b0, s) + 1; // 重なった年数（マイナス＝離れている年数）
  if (ov >= 2) return 0.88;
  if (ov >= 1) return 0.7;
  return 0.05 + 0.65 * Math.exp(-((1 - ov) ** 2) / 2.5);
}
