// [年, 値] の表を直線でつないで読む
function tbl(t, y) {
  if (y <= t[0][0]) return t[0][1];
  for (let i = 1; i < t.length; i++) if (y <= t[i][0]) {
    const [y0, v0] = t[i - 1], [y1, v1] = t[i]; return v0 + (v1 - v0) * (y - y0) / (y1 - y0);
  }
  return t[t.length - 1][1];
}

